/**
 * Property Automation API gateway (server-only).
 *
 * Thin, allow-listed proxy from the Next.js server to the Spring Boot Claude integration
 * endpoints (/api/v1/integrations/claude/**). Used only by the route handlers under
 * src/app/api/property-automation/. Not imported by any page or client component.
 *
 * Two independent credentials:
 *   X-Property-Automation-Gateway-Key  -> checked HERE (PROPERTY_AUTOMATION_GATEWAY_KEY)
 *   Authorization: Bearer <backend JWT> -> forwarded untouched, checked by Spring Boot
 *
 * Environment (server-side only; never NEXT_PUBLIC_):
 *   MPF_BACKEND_URL                                    e.g. http://localhost:8005
 *   PROPERTY_AUTOMATION_GATEWAY_KEY                    long random secret (gateway disabled when unset)
 *   PROPERTY_AUTOMATION_MAX_UPLOAD_BYTES               default 10485760 (10 MB)
 *   PROPERTY_AUTOMATION_UPLOAD_TIMEOUT_MS              default 600000 (10 min)
 *   PROPERTY_AUTOMATION_READ_TIMEOUT_MS                default 30000
 *   PROPERTY_AUTOMATION_RATE_LIMIT_PER_MINUTE          default 60  (all requests, per client IP)
 *   PROPERTY_AUTOMATION_UPLOAD_RATE_LIMIT_PER_MINUTE   default 10  (validate/import, per client IP)
 *   PROPERTY_AUTOMATION_AUTH_FAILURES_PER_MINUTE       default 10  (bad/missing gateway key, per client IP)
 */
import crypto from "node:crypto";

const BACKEND_API_PREFIX = "/api/v1/integrations/claude";
const GATEWAY_KEY_HEADER = "x-property-automation-gateway-key";
const JOB_ID_PATTERN = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;

/** Response headers copied from Spring Boot. Everything else (Set-Cookie, Server, ...) is dropped. */
const PASSTHROUGH_RESPONSE_HEADERS = ["content-type", "content-disposition", "retry-after"];

function intEnv(name, fallback) {
  const n = Number.parseInt(process.env[name] ?? "", 10);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

function config() {
  return {
    backendUrl: String(process.env.MPF_BACKEND_URL || "").trim().replace(/\/+$/, ""),
    gatewayKey: String(process.env.PROPERTY_AUTOMATION_GATEWAY_KEY || ""),
    maxUploadBytes: intEnv("PROPERTY_AUTOMATION_MAX_UPLOAD_BYTES", 10 * 1024 * 1024),
    uploadTimeoutMs: intEnv("PROPERTY_AUTOMATION_UPLOAD_TIMEOUT_MS", 10 * 60 * 1000),
    readTimeoutMs: intEnv("PROPERTY_AUTOMATION_READ_TIMEOUT_MS", 30 * 1000),
    ratePerMinute: intEnv("PROPERTY_AUTOMATION_RATE_LIMIT_PER_MINUTE", 60),
    uploadRatePerMinute: intEnv("PROPERTY_AUTOMATION_UPLOAD_RATE_LIMIT_PER_MINUTE", 10),
    authFailuresPerMinute: intEnv("PROPERTY_AUTOMATION_AUTH_FAILURES_PER_MINUTE", 10),
  };
}

/* ------------------------------------------------------------------ responses */

const SECURITY_HEADERS = {
  "Cache-Control": "no-store",
  "X-Content-Type-Options": "nosniff",
  "X-Robots-Tag": "noindex, nofollow",
};

/** Error generated by the gateway itself (same shape as the backend: timestamp/status/error/message). */
export function gatewayError(status, error, message, extraHeaders = {}) {
  return new Response(
    JSON.stringify({
      timestamp: new Date().toISOString(),
      status,
      error,
      message,
      source: "gateway",
    }),
    {
      status,
      headers: { "Content-Type": "application/json", ...SECURITY_HEADERS, ...extraHeaders },
    },
  );
}

/* ------------------------------------------------------------------ rate limiting */

const buckets = globalThis.__mpfPropertyAutomationBuckets || new Map();
globalThis.__mpfPropertyAutomationBuckets = buckets;

/** Fixed one-minute window counter. Returns seconds to wait, or 0 when allowed. */
function hit(key, limit) {
  const now = Date.now();
  const windowStart = now - (now % 60000);
  const b = buckets.get(key);
  if (!b || b.windowStart !== windowStart) {
    buckets.set(key, { windowStart, count: 1 });
    if (buckets.size > 5000) {
      for (const [k, v] of buckets) if (v.windowStart !== windowStart) buckets.delete(k);
    }
    return 0;
  }
  b.count += 1;
  return b.count > limit ? Math.ceil((windowStart + 60000 - now) / 1000) : 0;
}

function peek(key, limit) {
  const now = Date.now();
  const windowStart = now - (now % 60000);
  const b = buckets.get(key);
  return b && b.windowStart === windowStart && b.count >= limit
    ? Math.ceil((windowStart + 60000 - now) / 1000)
    : 0;
}

function clientIp(request) {
  const xff = request.headers.get("x-forwarded-for");
  if (xff) return xff.split(",")[0].trim();
  return request.headers.get("x-real-ip") || "local";
}

function tooMany(retryAfter, what) {
  return gatewayError(429, "RATE_LIMITED", `Too many ${what}. Retry after ${retryAfter} seconds.`, {
    "Retry-After": String(retryAfter),
  });
}

/* ------------------------------------------------------------------ authentication */

function keysMatch(provided, expected) {
  // Hash both sides so timingSafeEqual always compares equal-length buffers.
  const a = crypto.createHash("sha256").update(provided, "utf8").digest();
  const b = crypto.createHash("sha256").update(expected, "utf8").digest();
  return crypto.timingSafeEqual(a, b);
}

/**
 * Gateway checks shared by every route: configuration, rate limits, gateway key, Bearer header.
 * Returns { ok: true, cfg, authorization } or { ok: false, response }.
 */
function guard(request, { upload }) {
  const k = guardKey(request, { upload });
  if (!k.ok) return k;
  const { cfg } = k;

  const authorization = request.headers.get("authorization") || "";
  if (!/^Bearer\s+\S+$/i.test(authorization)) {
    return {
      ok: false,
      response: gatewayError(401, "JWT_MISSING", "Missing backend JWT. Send 'Authorization: Bearer <backend JWT>'."),
    };
  }
  // Structural check only (the backend verifies signature and expiry). The existing backend JWT
  // filter answers a garbled token with HTTP 500, so malformed tokens are refused here with 401.
  if (!looksLikeJwt(authorization.replace(/^Bearer\s+/i, ""))) {
    return {
      ok: false,
      response: gatewayError(401, "JWT_MALFORMED", "The backend JWT is malformed. Log in again and send the 'token' value from the login response."),
    };
  }
  return { ok: true, cfg, authorization };
}

/**
 * Configuration, lockout, gateway key and rate-limit checks (no JWT check).
 * Exported for the ChatGPT Actions routes, which obtain the backend JWT server-side.
 * Returns { ok: true, cfg } or { ok: false, response }.
 */
export function guardKey(request, { upload }) {
  const cfg = config();
  const ip = clientIp(request);

  if (!cfg.gatewayKey || cfg.gatewayKey.length < 24) {
    return { ok: false, response: gatewayError(503, "GATEWAY_DISABLED", "The property automation gateway is not configured on this server.") };
  }
  if (!cfg.backendUrl) {
    return { ok: false, response: gatewayError(503, "GATEWAY_DISABLED", "The backend URL is not configured on this server.") };
  }

  const blocked = peek(`fail:${ip}`, cfg.authFailuresPerMinute);
  if (blocked) return { ok: false, response: tooMany(blocked, "failed gateway authentication attempts") };

  const provided = request.headers.get(GATEWAY_KEY_HEADER);
  if (!provided) {
    hit(`fail:${ip}`, cfg.authFailuresPerMinute);
    return { ok: false, response: gatewayError(401, "GATEWAY_KEY_MISSING", "Missing X-Property-Automation-Gateway-Key header.") };
  }
  if (!keysMatch(provided, cfg.gatewayKey)) {
    hit(`fail:${ip}`, cfg.authFailuresPerMinute);
    return { ok: false, response: gatewayError(403, "GATEWAY_KEY_INVALID", "Invalid gateway key.") };
  }

  const wait = hit(`all:${ip}`, cfg.ratePerMinute) || (upload ? hit(`upload:${ip}`, cfg.uploadRatePerMinute) : 0);
  if (wait) return { ok: false, response: tooMany(wait, upload ? "upload requests" : "requests") };

  return { ok: true, cfg };
}

/**
 * Same lockout / constant-time comparison / rate limits as guardKey, but for a secret that does
 * not arrive in the gateway-key header (the MCP endpoint receives its key in the URL path, because
 * ChatGPT and Claude MCP connectors cannot send custom headers).
 * Returns { ok: true, cfg } or { ok: false, response }.
 */
export function guardSecret(request, provided, expected, { upload, label }) {
  const cfg = config();
  const ip = clientIp(request);
  if (!expected || expected.length < 24 || !cfg.backendUrl) {
    return { ok: false, response: gatewayError(503, "GATEWAY_DISABLED", `The ${label} is not configured on this server.`) };
  }
  const blocked = peek(`fail:${ip}`, cfg.authFailuresPerMinute);
  if (blocked) return { ok: false, response: tooMany(blocked, "failed authentication attempts") };
  if (!provided || !keysMatch(provided, expected)) {
    hit(`fail:${ip}`, cfg.authFailuresPerMinute);
    return { ok: false, response: gatewayError(404, "NOT_FOUND", "Not found.") };
  }
  const wait = hit(`all:${ip}`, cfg.ratePerMinute) || (upload ? hit(`upload:${ip}`, cfg.uploadRatePerMinute) : 0);
  if (wait) return { ok: false, response: tooMany(wait, upload ? "upload requests" : "requests") };
  return { ok: true, cfg };
}

/** Upload-rate check for an already-authenticated request (MCP tools/call that uploads). */
export function uploadRateExceeded(request) {
  const cfg = config();
  return hit(`upload:${clientIp(request)}`, cfg.uploadRatePerMinute);
}

function looksLikeJwt(token) {
  const parts = token.split(".");
  if (parts.length !== 3 || parts.some((p) => !/^[A-Za-z0-9_-]+$/.test(p))) return false;
  try {
    const header = JSON.parse(Buffer.from(parts[0], "base64url").toString("utf8"));
    const payload = JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8"));
    return typeof header === "object" && header !== null && typeof payload === "object" && payload !== null;
  } catch {
    return false;
  }
}

/* ------------------------------------------------------------------ forwarding */

function sanitizeUpstreamError(upstream) {
  // Spring Boot JSON errors are passed through unchanged. Non-JSON error bodies (e.g. a Tomcat
  // HTML page) are replaced so server internals never reach the client.
  return gatewayError(
    upstream.status,
    upstream.status === 413 ? "PAYLOAD_TOO_LARGE" : "BACKEND_ERROR",
    upstream.status === 413
      ? "The backend rejected the upload as too large."
      : `The backend returned HTTP ${upstream.status} without a JSON body.`,
  );
}

export async function forward(cfg, { method, path, query, authorization, contentType, body, timeoutMs }) {
  const url = new URL(cfg.backendUrl + BACKEND_API_PREFIX + path);
  if (query) for (const [k, v] of query) url.searchParams.append(k, v);

  const headers = { Authorization: authorization, Accept: "application/json, application/octet-stream, */*" };
  if (contentType) headers["Content-Type"] = contentType; // original value incl. multipart boundary

  const started = Date.now();
  let upstream;
  try {
    upstream = await fetch(url, {
      method,
      headers,
      body,
      duplex: body ? "half" : undefined,
      redirect: "manual",
      cache: "no-store",
      signal: AbortSignal.timeout(timeoutMs),
    });
  } catch (err) {
    const name = err?.name || "";
    const code = err?.cause?.code || err?.code || "";
    console.warn(`[property-automation] ${method} ${path} -> network error ${name || code} (${Date.now() - started} ms)`);
    if (name === "TimeoutError" || name === "AbortError") {
      return gatewayError(504, "BACKEND_TIMEOUT", `The backend did not respond within ${Math.round(timeoutMs / 1000)} seconds.`);
    }
    if (["ECONNREFUSED", "ENOTFOUND", "EHOSTUNREACH", "ECONNRESET", "UND_ERR_SOCKET"].includes(code)) {
      return gatewayError(503, "BACKEND_UNAVAILABLE", "The backend is not reachable. Is Spring Boot running?");
    }
    return gatewayError(502, "BAD_GATEWAY", "The request to the backend failed.");
  }

  console.info(`[property-automation] ${method} ${path} -> ${upstream.status} (${Date.now() - started} ms)`);

  const upstreamType = upstream.headers.get("content-type") || "";
  if (upstream.status >= 400 && !upstreamType.includes("json")) {
    try { await upstream.body?.cancel(); } catch { /* ignore */ }
    return sanitizeUpstreamError(upstream);
  }
  if (upstream.status >= 300 && upstream.status < 400) {
    try { await upstream.body?.cancel(); } catch { /* ignore */ }
    return gatewayError(502, "BAD_GATEWAY", `Unexpected redirect from the backend (HTTP ${upstream.status}).`);
  }

  const out = new Headers(SECURITY_HEADERS);
  for (const h of PASSTHROUGH_RESPONSE_HEADERS) {
    const v = upstream.headers.get(h);
    if (v) out.set(h, v);
  }
  return new Response(upstream.body, { status: upstream.status, headers: out });
}

/* ------------------------------------------------------------------ public helpers for routes */

/** Multipart POST (validate / import). Streams the original body; boundary and bytes are untouched. */
export async function proxyMultipart(request, { path, allowedQuery = [] }) {
  const g = guard(request, { upload: true });
  if (!g.ok) return g.response;

  const contentType = request.headers.get("content-type") || "";
  if (!/^multipart\/form-data;\s*boundary=/i.test(contentType)) {
    return gatewayError(
      415,
      "UNSUPPORTED_MEDIA_TYPE",
      "Send the files as multipart/form-data (field 'excelFile', optional 'imagesZip').",
    );
  }
  const declared = Number.parseInt(request.headers.get("content-length") || "", 10);
  if (Number.isFinite(declared) && declared > g.cfg.maxUploadBytes) {
    return gatewayError(
      413,
      "PAYLOAD_TOO_LARGE",
      `Upload is ${declared} bytes; this gateway accepts at most ${g.cfg.maxUploadBytes} bytes per request.`,
    );
  }
  if (!request.body) {
    return gatewayError(400, "EMPTY_BODY", "The multipart request body is empty.");
  }

  const query = filterQuery(request, allowedQuery);
  return forward(g.cfg, {
    method: "POST",
    path,
    query,
    authorization: g.authorization,
    contentType,
    body: request.body,
    timeoutMs: g.cfg.uploadTimeoutMs,
  });
}

/** GET (jobs / results / template). */
export async function proxyGet(request, { path, allowedQuery = [] }) {
  const g = guard(request, { upload: false });
  if (!g.ok) return g.response;
  return forward(g.cfg, {
    method: "GET",
    path,
    query: filterQuery(request, allowedQuery),
    authorization: g.authorization,
    timeoutMs: g.cfg.readTimeoutMs,
  });
}

function filterQuery(request, allowed) {
  const src = new URL(request.url).searchParams;
  const out = [];
  for (const name of allowed) {
    const v = src.get(name);
    if (v !== null) out.push([name, v]);
  }
  return out;
}

export function isValidJobId(jobId) {
  return typeof jobId === "string" && JOB_ID_PATTERN.test(jobId);
}

/** 405 for methods a route does not support (keeps the surface explicit). */
export function methodNotAllowed(allow) {
  return gatewayError(405, "METHOD_NOT_ALLOWED", `Use ${allow}.`, { Allow: allow });
}
